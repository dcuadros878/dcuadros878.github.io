function copyText(){
    const text = document.getElementById("textToCopy").innerText;
    navigator.clipboard.writeText(text)
    .then(()=>{
        alert("text copied");
    })
    .catch(err => {
        console.log('failed to copy due to : ' + err);
    })
}

